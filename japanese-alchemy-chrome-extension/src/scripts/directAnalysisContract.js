- 文法（Grammar）：真正的語法結構／功能（助詞用法、態、接續、句型框架、書面語中的連用中止等語法現象）。
- 搭配（Collocations／搭配）：慣常一起出現的詞組（名詞＋動詞、名詞＋名詞），語法上規則、但選詞固定或半固定。
