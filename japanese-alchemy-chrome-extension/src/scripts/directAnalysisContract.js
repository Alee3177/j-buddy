export function getSystemPrompt(promptVariant = DEFAULT_PROMPT_VARIANT) {
  return promptVariant === 'v1' ? SYSTEM_PROMPT_V1 : SYSTEM_PROMPT_V2;
}

export function buildDirectAnalysisMessage(content, context) {
  const beforeRaw = typeof context?.before === 'string' ? context.before : '';
  const afterRaw = typeof context?.after === 'string' ? context.after : '';
  const cleanContext = (value) => value
    .replace(DELIMITER_PATTERN, '')
    .trim()
    .slice(0, MAX_CONTEXT_CHARS);
  const before = cleanContext(beforeRaw);
  const after = cleanContext(afterRaw);

  if (!before && !after) return content;

  const parts = [];
  if (before) parts.push(`${CONTEXT_BEFORE_LABEL}${before}`);
  parts.push(`${TARGET_LABEL}${content}`);
  if (after) parts.push(`${CONTEXT_AFTER_LABEL}${after}`);
  return parts.join('\n');
}

export function buildDirectCompletionRequest({ profile, selectedText, promptVariant, context, stream }) {
  return {
    model: profile.model,
    messages: [
      { role: 'system', content: getSystemPrompt(promptVariant) },
      { role: 'user', content: buildDirectAnalysisMessage(selectedText, context) },
    ],
    temperature: 0.1,
    max_tokens: 8192,
    stream: Boolean(stream),
  };
}

export function buildDirectResponsesRequest({ profile, selectedText, promptVariant, context, stream }) {
  return {
    model: profile.model,
    instructions: getSystemPrompt(promptVariant),
    input: buildDirectAnalysisMessage(selectedText, context),
    max_output_tokens: 8192,
    stream: Boolean(stream),
    store: false,
  };
}
